#!/usr/bin/env python3
"""Bundle local Luau source modules into one paste-runnable, HTTP-free script."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "executor/Source"
SOURCES = [
    ("Maid", ()),
    ("Theme", ()),
    ("Library", ("Theme", "Maid")),
    ("PrivateContext", ()),
    ("Targeting", ("PrivateContext",)),
    ("Movement", ("PrivateContext", "Maid")),
    ("Visuals", ("PrivateContext", "Maid", "Theme")),
    ("Combat", ("PrivateContext", "Maid")),
    ("Travel", ("PrivateContext",)),
    ("Inventory", ("PrivateContext",)),
    ("Vehicles", ("PrivateContext",)),
    ("PrivateMenu", ()),
    ("PrivateCore", ("PrivateContext", "Maid", "Library", "PrivateMenu",
                     "Targeting", "Movement", "Visuals", "Combat", "Travel", "Inventory", "Vehicles")),
]


def module(name: str, dependencies: tuple[str, ...]) -> str:
    text = (SOURCE / f"{name}.lua").read_text(encoding="utf-8")
    parameters = ", ".join(dependency + "Module" for dependency in dependencies)
    arguments = ", ".join(dependencies)
    return "\n".join(
        (f"-- {name}.", f"local function load{name}({parameters})", text.rstrip(),
         "end", f"local {name} = load{name}({arguments})", "")
    )


def render() -> str:
    header = """-- amethyst / prison life private client. generated by tools/build_private.py
-- paste this whole file into a Luau executor while in an official private server.
-- no external HTTP loader, no installed server scripts, no public-server execution.
"""
    body = header + "\n".join(module(name, dependencies) for name, dependencies in SOURCES)
    body += """
-- Start after all modules have loaded so startup errors remain visible.
local ok = xpcall(PrivateCore.start, function(message)
	warn("[amethyst] startup failed: ", message)
	if debug and type(debug.traceback) == "function" then warn(debug.traceback()) end
end)
if not ok then warn("[amethyst] private hub did not start") end
"""
    return body


def main() -> None:
    output = ROOT / "executor/AmethystPrivate.lua"
    body = render()
    output.write_text(body, encoding="utf-8")
    print(f"wrote {output.relative_to(ROOT)} ({len(body.splitlines())} lines)")


if __name__ == "__main__":
    main()
